"""Generate the rail-crossing set's crossbuck (ledger 0096, Denver Grand Prix PLAN §4b) — deterministic, self-made
(CC0). The set's other half, the light-rail bar signal, is `signal_head_lrt_2` in tools/make_signals.py; the faces
(R15-1 blades, the W10-1 advance disc) are in tools/make_sign_faces.py.

WHETHER A CROSSBUCK STANDS ON THE LAP IS NOT KNOWN. OSM tags the lap's five rail crossings as light-rail level
crossings, four of them `crossing:light = traffic_signals` — tracks in the street, governed by the junction's own
signals — and where a signal governs a crossing a crossbuck is usually absent. The survey decides (PLAN §4b: never
`invented`); this is the model for the case that it finds one.

DIMENSIONS (MUTCD 2009; written from knowledge of that edition, not re-read in the session that wrote this):
  blades        two, 48 x 9 in, crossed at 90 degrees         MUTCD 8B.03 (R15-1)
  centre        9 ft above the ground                          MUTCD Figure 8B-2 as recalled — CHECK before leaning on it
  post          NPS 4 pipe (4.5 in OD), 11.5 ft                [typical]
  RAILROAD reads from the upper left to the lower right, CROSSING from the lower left to the upper right, and the
  CROSSING blade lies on top (which is why the RAILROAD face is drawn split).

FRAME: metres, +y up, origin = the post axis at the ground, the faces look along +z (the reader's right is +x).
Objects: POST (SIGNPOST); FACE_RAILROAD / FACE_CROSSING (SIGNFACE_R15-1_RAILROAD / _CROSSING, UV 0..1 = the blade's
rectangle, textures mutcd_r15-1_railroad.png / mutcd_r15-1_crossing.png); BACKS (SIGNBACK).

    python tools/make_rail_crossing.py [--check]
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from street_furniture_mesh import FT, IN, Model, write_or_check          # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "assets" / "models"
BLADE = (48 * IN, 9 * IN)             # MUTCD 8B.03
CENTRE_Y = 9 * FT                     # MUTCD Figure 8B-2, as recalled
POST_R, POST_H, POST_BURY = 4.5 * IN / 2, 11.5 * FT, 0.5      # [typical]
UV = ((0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0))


def _blade(deg: float, z: float):
    d = (math.cos(math.radians(deg)), math.sin(math.radians(deg)))
    n = (-d[1], d[0])
    a, b = BLADE[0] / 2, BLADE[1] / 2
    return [(sx * a * d[0] + sy * b * n[0], CENTRE_Y + sx * a * d[1] + sy * b * n[1], z) for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]


def crossbuck() -> Model:
    m = Model("rail_crossbuck", "railroad crossbuck (R15-1) on its post", "metres, +y up, origin = post axis at the ground, faces look along +z",
              "tools/make_rail_crossing.py")
    m.obj("POST", "SIGNPOST").tube([(0.0, -POST_BURY, 0.0), (0.0, POST_H, 0.0)], [POST_R, POST_R], 8)
    backs = m.obj("BACKS", "SIGNBACK")
    for word, deg, z in (("RAILROAD", -45.0, POST_R + 0.004), ("CROSSING", 45.0, POST_R + 0.010)):
        q = _blade(deg, z)
        m.obj(f"FACE_{word}", f"SIGNFACE_R15-1_{word}").polygon(q, UV, (0.0, 0.0, 1.0))
        backs.polygon([(x, y, z - 0.002) for x, y, _ in q], UV, (0.0, 0.0, -1.0))
    return m


def outputs() -> dict[str, str]:
    m = crossbuck()
    spec = {"name": "rail_crossing", "_doc": "ledger 0096 — the crossbuck, generated by tools/make_rail_crossing.py. Whether one stands on "
            "Denver's lap is for the survey: OSM tags the five crossings as light rail under traffic signals. Not placed on any track.",
            "crossbuck": {"file": "rail_crossbuck.obj", "blade_m": [round(c, 4) for c in BLADE], "centre_height_m": round(CENTRE_Y, 4),
                          "post_height_m": round(POST_H, 4), "post_radius_m": round(POST_R, 4),
                          "textures": {"SIGNFACE_R15-1_RAILROAD": "mutcd_r15-1_railroad.png", "SIGNFACE_R15-1_CROSSING": "mutcd_r15-1_crossing.png",
                                       "SIGNPOST": "solid_metal_grey.png", "SIGNBACK": "solid_metal_grey.png"}, **m.summary()},
            "light_rail_signal": "signal_head_lrt_2.obj (assets/models/signals.json, tools/make_signals.py)",
            "advance_warning": "mutcd_w10-1.png on sign_plate_circle_36.obj (assets/models/sign_faces.json)",
            "sources": {"blades": "MUTCD 2009 8B.03: Crossbuck (R15-1), two 48 x 9 in blades at right angles",
                        "height": "MUTCD 2009 Figure 8B-2 (about 9 ft to the centre) — recalled, not re-read: check",
                        "typical": "post NPS 4, 11.5 ft"}}
    return {"rail_crossbuck.obj": m.text(), "rail_crossing.json": json.dumps(spec, indent=1) + "\n"}


if __name__ == "__main__":
    sys.exit(write_or_check(OUT, outputs(), sys.argv[1:], "rail-crossing"))
